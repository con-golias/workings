# Pulls every US Copyright Office public record that matches an AI phrase or an AI coding phrase, then the full
# record of each. Public records API (api.publicrecords.copyright.gov), the same one the Public Records System site uses.
# The first 11 phrases are the 20 Nov copyright article's (read 9 Nov); the rest are added here for code.
# Full records already pulled for that article are read from OLD_RAW and not fetched again; new ones go to RAW.
# Both folders are git-ignored: full records hold claimant street addresses.
#   python code/fetch.py
import json, urllib.request, urllib.parse, time, os, concurrent.futures as cf
B = "https://api.publicrecords.copyright.gov/search_service_external/"
here = os.path.dirname(os.path.abspath(__file__))
RAW = os.environ.get("RAW", os.path.join(here, "..", "data", "raw"))
OLD_RAW = os.environ.get("OLD_RAW", os.path.join(here, "..", "..", "2026-11-11-copyright-ai-disclaimers", "data", "raw"))
def get(u):
    for k in range(6):
        try: return json.load(urllib.request.urlopen(urllib.request.Request(u, headers={"User-Agent": "curl/8.0"}), timeout=90))
        except Exception: time.sleep(2 + k * 2)
    return None
Q_OLD = ['"AI-generated"', '"artificial intelligence"', '"generated by AI"', '"AI-assisted"', 'Midjourney', 'ChatGPT', 'Suno', 'Udio',
         '"Stable Diffusion"', 'DALL-E', '"generative AI"']
Q_CODE = ['"AI-generated code"', '"AI generated code"', '"generated code"', '"code generated"', 'Copilot', '"Cursor"', 'Codex',
          '"Claude Code"', '"Claude AI"', 'Anthropic', 'OpenAI', '"large language model"', 'LLM', '"machine-generated"',
          '"AI tools"', '"AI-written"', '"AI coding"', '"vibe coding"', '"AI-assisted code"', '"Amazon Q"', '"Gemini Code"', '"AI code"',
          # second round, 25 Nov (Adobe's "code created by AI agents" was found only through its product name)
          '"AI agent"', '"AI assistant"', '"code assistant"', '"auto-generated"', 'GenAI', '"Gen AI"', '"AI-created"', '"created by AI"', '"Replit"',
          '"coding agent"', '"AI-powered"', '"using AI"', '"AI-enabled"', '"assisted by AI"', '"AI models"']
Q = Q_OLD + Q_CODE
def ql(q):
    out, p = [], 1
    while True:
        d = get(B + "simple_search_dsl?" + urllib.parse.urlencode({"page_number": p, "query": q, "field_type": "keyword", "records_per_page": 100}))
        if d is None: print("FAILED", q, p, flush=True); break
        h = d.get("data") or []; out += [x["hit"]["public_records_id"] for x in h]
        if len(h) < 100: break
        p += 1
    return q, out
ids = {}
with cf.ThreadPoolExecutor(4) as ex:
    for q, o in ex.map(ql, Q):
        print(q, len(o), flush=True)
        for i in o: ids.setdefault(i, []).append(q)
json.dump(ids, open(os.path.join(here, "..", "data", "ids.json"), "w")); print("unique", len(ids), flush=True)
os.makedirs(RAW, exist_ok=True)
def full(i):
    if os.path.exists(os.path.join(OLD_RAW, i + ".json")) or os.path.exists(os.path.join(RAW, i + ".json")): return
    d = get(B + "search_unique_record?" + urllib.parse.urlencode({"query": i}))
    if d: json.dump(d, open(os.path.join(RAW, i + ".json"), "w"))
todo = [i for i in ids if not os.path.exists(os.path.join(OLD_RAW, i + ".json"))]
print("to fetch", len(todo), flush=True)
n = 0
with cf.ThreadPoolExecutor(12) as ex:
    for _ in ex.map(full, todo):
        n += 1
        if n % 500 == 0: print("full", n, flush=True)
print("done new", len(os.listdir(RAW)), flush=True)
