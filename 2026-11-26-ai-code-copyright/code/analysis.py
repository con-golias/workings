# AI phrase: the 20 Nov list plus the coding assistants and their makers.
AI = re.compile(r"\bA\.?I\b\.?|artificial[ -]intelligence|machine[ -]generated|"
                r"midjourney|chat ?gpt|\bgpt-?\d|suno|\budio\b|dall[- ]?e|stable diffusion|leonardo\.?ai|firefly|"
                r"\bsora\b|runway|elevenlabs|eleven labs|\bclaude\b|\bgemini\b|copilot|\bllm s?\b|\bllms?\b|large language model|"
                r"openai|anthropic|\bcodex\b|cursor ai|\bcursor (?:ide|editor)\b|windsurf|amazon q\b|codewhisperer|tabnine|"
                # read by hand, 25 Nov: Apple's Xcode assistant, and a misspelling in one record
                r"swift assist|artificial[ -]inetlligence", re.I)
TOOLS = [("ChatGPT / OpenAI GPT", r"chat ?gpt|\bgpt-?\d|openai(?! codex)"), ("Copilot", r"copilot"), ("Claude", r"\bclaude\b|anthropic"),
         ("Gemini", r"\bgemini\b"), ("Codex", r"\bcodex\b"), ("Cursor", r"cursor ai|\bcursor (?:ide|editor)\b|\bcursor\b(?=[^.;]{0,40}\bAI\b)|\bAI\b[^.;]{0,40}\bcursor\b"), ("Bolt", r"\(bolt\)|\bbolt\.new\b"),
         ("Amazon Q / CodeWhisperer", r"amazon q\b|codewhisperer"), ("Windsurf", r"windsurf"), ("Tabnine", r"tabnine"),
         ("watsonx", r"watsonx"), ("Swift Assist", r"swift assist")]
CODE = re.compile(r"\bcodes?\b|source code|computer program|program text|programm?ing|snippet|test cases", re.I)
ORG = re.compile(r"\b(LLC|Inc|Corporation|Corp|Ltd|Limited|GmbH|Company|Co\b|LLP|PBC|Studios?|Media|Publishing|Records|Group|AG|S\.?A\.?|B\.?V\.?|PLC|Technologies|Systems|Labs?)\b")


# For code, "machine-generated" is not enough: it usually means code generators and compilers, not AI
# (read by hand, 25 Nov: "machine-generated XML code", "Go compiler-provided source code, … machine-generated source code").
AI_CODE = re.compile(AI.pattern.replace(r"machine[ -]generated|", ""), re.I)


def ai_bits(s, pat=AI):
    return [p.strip() for p in re.split(r"[;,]|\.\s|\band\b|&", s or "") if pat.search(p)]


def is_code(stmt):
    stmt = re.sub(r"\bgen\.\s", "generated ", stmt or "", flags=re.I)  # "AI-gen. code" (found in the random sample, 25 Nov)
    # code only when an AI-bearing piece names code, or "AI-generated <...code...>" names it right after the phrase
    if any(CODE.search(b) for b in ai_bits(stmt, AI_CODE)): return True
    m = re.search(r"(?:\bAI\b|artificial intelligence)[- ](?:generated|assisted|created)\s+([^;.]+)", stmt or "", re.I)
    if m and CODE.search(m.group(1)): return True
    # "source code and HTML generated by artificial intelligence": the clause before "generated by AI" names code
    m = re.search(r"([^;.,]+?)\s+(?:originally )?generated by (?:an? )?(?:\bAI\b|artificial intelligence)", stmt, re.I)
    return bool(m and CODE.search(m.group(1)))


def rec(path):
    d = json.load(open(path, encoding="utf-8")); r = (d.get("data") or [{}])[0]; return r.get("hit", r)


def path_of(i):
    for d in RAWS:
        p = os.path.join(d, i + ".json")
        if os.path.exists(p): return p


# Read by hand: the rule matches, but the code is not the AI part ("AI-generated artwork, preexisting screenshots and source code")
NOT_CODE = {"TX0009635300",
            "TX0009525239"}  # "OpenAI Base Code": code written by OpenAI, excluded as third-party code, not AI output
# Read by hand: the rule misses it, but the statement does exclude AI-written code
ADD_CODE = {"TX0009596268"}  # "short, unrevised code snippets, functional/non-creative boilerplate code, … originally generated by artificial intelligence or provided as open-source components"
seen, rows, regs, any_ai, claimed_side = set(), [], 0, 0, []
files = {f[:-5] for d in RAWS if os.path.isdir(d) for f in os.listdir(d) if f.endswith(".json")}
for i in sorted(files):
    r = rec(path_of(i))
    if not r or r.get("type_of_record") != "registration": continue
    rn = r.get("registration_number")
    if isinstance(rn, list): rn = rn[0] if rn else None
    if not rn or rn in seen: continue
    seen.add(rn); regs += 1
    ex = r.get("material_excluded_statement") or ""
    inc = " ".join(x.get("material_included_statement", "") for x in r.get("material_included_list") or [])
    auth = " ".join(x.get("author_authorship_statement", "") for x in r.get("author_statement_list") or [])
    if AI.search(ex) or AI.search(inc) or AI.search(auth): any_ai += 1
    # the other way round: AI and code named in what the applicant CLAIMS, with no AI code in what it excludes
    if not (AI_CODE.search(ex) and is_code(ex)) and any(AI_CODE.search(s) and is_code(s) for s in (inc, auth)):
        claimed_side.append({"registration_number": rn, "date": r.get("registration_date") or "", "type": r.get("type_of_work_to_english"),
                             "excluded": ex, "included": inc, "authorship": auth})
    if not ((AI_CODE.search(ex) and is_code(ex)) or rn in ADD_CODE): continue
    if rn in NOT_CODE: continue
    claimants = [c.get("claimant_full_name", "").strip().rstrip(",.;") for c in r.get("claimants_list") or []]
    allstmt = " ".join((ex, inc, auth))
    rows.append({"registration_number": rn, "registration_date": r.get("registration_date") or "",
                 "type_of_work": r.get("type_of_work_to_english"), "claimant": "; ".join(claimants),
                 "org": any(ORG.search(c) for c in claimants) or any("hire" in (a.get("author_work_for_hire_statement") or "").lower() for a in r.get("author_statement_list") or []), "excluded": ex, "included": inc, "authorship": auth,
                 "tools": "+".join(n for n, p in TOOLS if re.search(p, allstmt, re.I)),
                 "title": r.get("title_concatenated") or "",
                 "note": " ".join(r.get("copyright_note") or []) if isinstance(r.get("copyright_note"), list) else (r.get("copyright_note") or ""),
                 "found_by": "+".join(sorted(set(IDS.get(i, [])))) if i in IDS else "(20 Nov pull)"})

S = {"records_read": len(files), "registrations_read": regs, "registrations_with_ai_statement": any_ai, "n": len(rows)}
rows.sort(key=lambda k: k["registration_date"])
S["first"] = rows[0]["registration_date"]
S["computer_files"] = sum(k["type_of_work"] == "Computer Files" for k in rows)
S["by_type"] = collections.Counter(k["type_of_work"] for k in rows).most_common()
S["by_year"] = dict(sorted(collections.Counter(k["registration_date"][:4] for k in rows if k["registration_date"]).items()))
S["orgs_n"] = sum(k["org"] for k in rows); S["individuals_n"] = len(rows) - S["orgs_n"]
oc = collections.Counter(re.sub(r"[,.]", "", k["claimant"].split("; ")[0]).strip() for k in rows if k["org"])
S["org_claimants"] = len(oc); S["orgs"] = oc.most_common()
S["org_single"] = sum(1 for n in oc.values() if n == 1)
S["only_new_phrases"] = sum(1 for k in rows if k["found_by"] != "(20 Nov pull)" and not any(q in k["found_by"] for q in
                         ['"AI-generated"', '"artificial intelligence"', '"generated by AI"', '"AI-assisted"', 'Midjourney', 'ChatGPT',
                          'Suno', 'Udio', '"Stable Diffusion"', 'DALL-E', '"generative AI"']))
S["tools_named"] = sum(bool(k["tools"]) for k in rows)
S["tools"] = collections.Counter(t for k in rows for t in k["tools"].split("+") if t).most_common()

# How the code is described (one excluded statement can fall in several groups)
W = {"office_wording": None,
     "third_party": r"third[- ]party|open[- ]source|librar|framework|by other companies|by third parties|pre-?existing|preexisting|previously published",
     "prior_version": r"prior version|previous version|including +versions|program versions|version\(s\)|initial versions",
     "size_words": r"\bsome\b|portions?|snippets?|minor bits|small pieces|fragments",
     "percent": r"\d+\s?%|\d+\s?-\s?\d+\s?%|\d+\s?percent",
     "process": r"chosen by|edited|direction|prompting|based on|under the author|manually tweaked|to create|to 1\)|for generating|assistance|assisted|suggestions",
     "hedged": r"\(if any\)|\bif any\b|may (?:have been|be|contain)|possibly|potentially|to the extent",
     "tool": None}
OFFICE0 = re.compile(r"^(?:computer program, )?(?:some )?(?:text and |html and )?(?:source code|computer program|computer code) generated by (?:an )?artificial intelligence(?: program)?\s?\.?$", re.I)
S["wording"] = {k: sum(bool(OFFICE0.match(x["excluded"].strip())) if k == "office_wording" else bool(x["tools"]) if k == "tool"
                       else bool(re.search(p, x["excluded"], re.I)) for x in rows) for k, p in W.items()}
