# Rate: AI-code registrations per 1,000 Computer Files registrations, complete quarters only (same lag rule)
cf_ai = collections.Counter(k["registration_date"][:7] for k in rows if k["type_of_work"] == "Computer Files" and k["registration_date"])
# A quarter is complete when its Computer Files count reaches 80% of 2025's median quarter (records arrive late)
CFQ = lambda y, q: sum(DEN[f"{y}-{m:02d}"]["type_of_work"].get("computer_file", 0) for m in range(3 * q + 1, 3 * q + 4))
MEDQ = statistics.median(CFQ(2025, q) for q in range(4))
S["by_quarter"] = []
for y in range(2023, 2027):
    for q in range(4):
        ms = [f"{y}-{m:02d}" for m in range(3 * q + 1, 3 * q + 4)]
        if any(m not in DEN for m in ms): continue
        a = sum(cf_ai.get(m, 0) for m in ms); t = sum(DEN[m]["type_of_work"].get("computer_file", 0) for m in ms)
        full = t >= 0.8 * MEDQ
        filers = len({k["claimant"] if k["org"] else k["registration_number"] for k in rows
                      if k["type_of_work"] == "Computer Files" and k["registration_date"][:7] in ms})
        S["by_quarter"].append({"q": f"{y} Q{q + 1}", "filers": filers, "ai_code": a, "computer_files": t, "per_1000": round(1e3 * a / t, 2) if t else None, "complete": full})
S["cf_2025"] = {"ai_code": sum(v for m, v in cf_ai.items() if m.startswith("2025")),
                "computer_files": sum(DEN[m]["type_of_work"].get("computer_file", 0) for m in DEN if m.startswith("2025"))}
S["cf_2025"]["one_in"] = round(S["cf_2025"]["computer_files"] / S["cf_2025"]["ai_code"]) if S["cf_2025"]["ai_code"] else None
S["cf_2025"]["pct"] = round(100 * S["cf_2025"]["ai_code"] / S["cf_2025"]["computer_files"], 2)
