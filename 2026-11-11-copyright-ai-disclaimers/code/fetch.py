# Pulls every US Copyright Office public record that matches an AI phrase, then the full record of each.
# Public records API (api.publicrecords.copyright.gov), the same one the Public Records System site uses.
# Raw full records go to RAW (default ../data/raw/, git-ignored: they hold claimant street addresses).
#   python3 code/fetch.py
import json,urllib.request,urllib.parse,sys,time,os,concurrent.futures as cf
B="https://api.publicrecords.copyright.gov/search_service_external/"
def get(u):
    for k in range(6):
        try: return json.load(urllib.request.urlopen(urllib.request.Request(u,headers={"User-Agent":"curl/8.0"}),timeout=90))
        except Exception as e: time.sleep(2+k*2)
    return None
Q=['"AI-generated"','"artificial intelligence"','"generated by AI"','"AI-assisted"','Midjourney','ChatGPT','Suno','Udio','"Stable Diffusion"','DALL-E','"generative AI"']
ids={}
def ql(q):
    out=[];p=1
    while True:
        d=get(B+"simple_search_dsl?"+urllib.parse.urlencode({"page_number":p,"query":q,"field_type":"keyword","records_per_page":100}))
        if d is None: print("FAILED",q,p,flush=True); break
        h=d.get("data") or []; out+=[x["hit"]["public_records_id"] for x in h]
        if len(h)<100: break
        p+=1
    return q,out
with cf.ThreadPoolExecutor(4) as ex:
    for q,o in ex.map(ql,Q):
        print(q,len(o),flush=True)
        for i in o: ids.setdefault(i,[]).append(q)
json.dump(ids,open(os.path.join(os.path.dirname(os.path.abspath(__file__)),"..","data","ids.json"),"w")); print("unique",len(ids),flush=True)
RAW=os.environ.get("RAW",os.path.join(os.path.dirname(os.path.abspath(__file__)),"..","data","raw")); os.makedirs(RAW,exist_ok=True)
def full(i):
    p=os.path.join(RAW,i+".json")
    if os.path.exists(p): return
    d=get(B+"search_unique_record?"+urllib.parse.urlencode({"query":i}))
    if d: json.dump(d,open(p,"w"))
n=0
with cf.ThreadPoolExecutor(12) as ex:
    for _ in ex.map(full,list(ids)):
        n+=1
        if n%1000==0: print("full",n,flush=True)
print("done",len(os.listdir(RAW)),flush=True)
